"""
Build a synthetic Sefer Torah column map for use as a fallback when the
PDF-derived profile is unavailable for a given column.

Uses the canonical Ashkenazi parameters: 248 columns × 42 lines per column.
The bundled Hebrew corpus letters are evenly distributed.
"""
import json
import re
from pathlib import Path

CORPUS = Path(__file__).parent / "data" / "torah_corpus.json"
OUT = Path(__file__).parent / "data" / "scroll_profiles" / "synthetic_248.json"

TORAH_BOOKS = ["Genesis", "Exodus", "Leviticus", "Numbers", "Deuteronomy"]
HEB_LETTER = re.compile(r"[\u05D0-\u05EA]")
NIKUD_TEAMIM = re.compile(r"[\u0591-\u05C7]")

COLUMNS = 248
LINES_PER_COLUMN = 42


def strip_nikud(s: str) -> str:
    return NIKUD_TEAMIM.sub("", s)


def main():
    with open(CORPUS, "r", encoding="utf-8") as f:
        corpus = json.load(f)
    stream = []
    for book_entry in corpus["books"]:
        if book_entry["en"] not in TORAH_BOOKS:
            continue
        book = book_entry["en"]
        for ch_idx, chapter in enumerate(book_entry["chapters"], start=1):
            for v_idx, verse in enumerate(chapter, start=1):
                for ch in strip_nikud(verse):
                    if HEB_LETTER.match(ch):
                        stream.append((book, ch_idx, v_idx, ch))

    total = len(stream)
    line_count = COLUMNS * LINES_PER_COLUMN
    base_per_line = total // line_count
    leftover = total - base_per_line * line_count
    line_counts = [base_per_line] * line_count
    # Distribute the leftover letters across the first `leftover` lines
    for i in range(leftover):
        line_counts[i] += 1

    cursor = 0
    columns = []
    for col_idx in range(COLUMNS):
        col = {"column": col_idx + 1, "lines": []}
        for line_idx in range(LINES_PER_COLUMN):
            n = line_counts[col_idx * LINES_PER_COLUMN + line_idx]
            chunk = stream[cursor:cursor + n]
            cursor += n
            verses = sorted(
                {(c[0], c[1], c[2]) for c in chunk},
                key=lambda v: (TORAH_BOOKS.index(v[0]), v[1], v[2]),
            )
            col["lines"].append({
                "line": line_idx + 1,
                "letter_count": n,
                "text_plain": "".join(c[3] for c in chunk),
                "verses": [{"book": b, "chapter": c, "verse": v} for b, c, v in verses],
            })
        col["opens_with"] = col["lines"][0]["verses"][0] if col["lines"][0]["verses"] else None
        col["closes_with"] = col["lines"][-1]["verses"][-1] if col["lines"][-1]["verses"] else None
        columns.append(col)

    profile = {
        "name": "synthetic_248",
        "title": "Synthetic 248-column Ashkenazi layout",
        "tradition": "Ashkenazi (canonical)",
        "source": "Generated by even letter-distribution: 248 columns × 42 lines × ~30 letters",
        "column_count": COLUMNS,
        "books_covered": TORAH_BOOKS,
        "columns": columns,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(profile, f, ensure_ascii=False, separators=(",", ":"))
    size_kb = OUT.stat().st_size / 1024
    print(f"Wrote {OUT} ({size_kb:.1f} KB)")
    print(f"  {COLUMNS} columns, {COLUMNS * LINES_PER_COLUMN} lines, "
          f"{base_per_line} letters/line (avg)")


if __name__ == "__main__":
    main()
